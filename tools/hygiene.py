#!/usr/bin/env python3
"""
tools/hygiene.py — Post-processing hygiene & realistic timestamp engine for .pptx decks.

Standard library + lxml only (zero network, zero pip install).
Usage:
  python3 tools/hygiene.py input.pptx --out output.pptx --author 作者名 --title 标题 [--now 2026-11-26T15:30] [--seed 42] [--brief] [--json]
Exit codes:
  0 = success
  1 = blocking error
  2 = CLI argument error
"""

import argparse
from collections import Counter
from datetime import datetime, timedelta
import json
import os
import random
import re
import sys
import zipfile
from lxml import etree

XML_DECL = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
XML_DECL_RE = re.compile(rb"^\s*<\?xml[^>]*\?>\s*", re.DOTALL)

NS = {
    "a": "http://schemas.openxmlformats.org/drawingml/2006/main",
    "p": "http://schemas.openxmlformats.org/presentationml/2006/main",
    "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships",
    "cp": "http://schemas.openxmlformats.org/package/2006/metadata/core-properties",
    "dc": "http://purl.org/dc/elements/1.1/",
    "dcterms": "http://purl.org/dc/terms/",
    "xsi": "http://www.w3.org/2001/XMLSchema-instance",
    "ep": "http://schemas.openxmlformats.org/officeDocument/2006/extended-properties",
}

A_NS = NS["a"]
P_NS = NS["p"]
CP_NS = NS["cp"]
DC_NS = NS["dc"]
DCTERMS_NS = NS["dcterms"]
XSI_NS = NS["xsi"]
EP_NS = NS["ep"]

CJK_CHAR_RE = re.compile(r"[\u4e00-\u9fff\u3400-\u4dbf]")
LATIN_WORD_RE = re.compile(r"[A-Za-z0-9]+(?:['’-][A-Za-z0-9]+)*")

KNOWN_CJK_FONT_TOKENS = (
    "yahei", "微软雅黑", "思源", "source han", "simsun", "simhei", "宋体", "黑体",
    "楷体", "仿宋", "kaiti", "fangsong", "pingfang", "苹方", "冬青", "hiragino",
    "方正", "华文", "汉仪", "站酷", "庞门", "霞鹜", "lxgw", "misans", "harmonyos",
    "stsong", "stheiti", "stkaiti", "stfangsong", "dengxian", "等线", "noto sans cjk",
    "noto serif cjk", "noto sans sc", "noto serif sc",
)

YAHEI_NAMES = {"microsoft yahei", "microsoft yahei ui", "微软雅黑"}

PLACEHOLDER_PATTERNS = (
    "python-pptx", "generated by", "待填写", "待补", "课题组", "template",
)

# Tags in a:rPr that must appear AFTER latin/ea/cs according to DrawingML schema
RPR_AFTER_FONT_TAGS = {
    f"{{{A_NS}}}sym",
    f"{{{A_NS}}}hlinkClick",
    f"{{{A_NS}}}hlinkMouseOver",
    f"{{{A_NS}}}rtl",
    f"{{{A_NS}}}extLst",
}


def is_cjk_font(font_name: str) -> bool:
    if not font_name:
        return False
    low = font_name.strip().lower()
    if CJK_CHAR_RE.search(font_name):
        return True
    return any(tok in low for tok in KNOWN_CJK_FONT_TOKENS)


def is_noto_font(font_name: str) -> bool:
    return bool(font_name) and "noto" in font_name.strip().lower()


def is_yahei(font_name: str) -> bool:
    return bool(font_name) and font_name.strip().lower() in YAHEI_NAMES


def count_words(text: str) -> int:
    if not text:
        return 0
    cjk_count = len(CJK_CHAR_RE.findall(text))
    latin_count = len(LATIN_WORD_RE.findall(text))
    return cjk_count + latin_count


def normalize_xml_declaration(raw_bytes: bytes) -> bytes:
    cleaned = XML_DECL_RE.sub(b"", raw_bytes, count=1)
    return (XML_DECL + "\n").encode("utf-8") + cleaned


def serialize_xml(root: etree._Element) -> bytes:
    body = etree.tostring(root, encoding="utf-8", xml_declaration=False)
    return (XML_DECL + "\n").encode("utf-8") + body


def detect_presentation_format(pres_bytes: bytes) -> str:
    root = etree.fromstring(pres_bytes)
    sld_sz = root.find(f"{{{P_NS}}}sldSz")
    if sld_sz is None:
        return "On-screen Show (16:9)"
    try:
        cx = int(sld_sz.get("cx", "0"))
        cy = int(sld_sz.get("cy", "0"))
    except ValueError:
        return "On-screen Show (16:9)"
    if cx <= 0 or cy <= 0:
        return "On-screen Show (16:9)"
    ratio = cx / cy
    if abs(ratio - (16.0 / 9.0)) < 0.08:
        return "On-screen Show (16:9)"
    if abs(ratio - (4.0 / 3.0)) < 0.08:
        return "On-screen Show (4:3)"
    if abs(ratio - (16.0 / 10.0)) < 0.08:
        return "On-screen Show (16:10)"
    return "Custom"


def pick_non_round_min_sec(rng: random.Random) -> tuple[int, int]:
    minutes = [m for m in range(1, 60) if m % 5 != 0]
    seconds = [s for s in range(1, 60) if s % 5 != 0]
    return rng.choice(minutes), rng.choice(seconds)


def generate_human_timestamps(
    now_dt: datetime, slide_count: int, rng: random.Random
) -> dict:
    # Span: 6-12 min per slide, clamped to [40, 480]
    raw_span = sum(rng.uniform(6.0, 12.0) for _ in range(max(1, slide_count)))
    span_minutes = int(round(max(40.0, min(480.0, raw_span))))

    # Choose a created time within the 3 days prior to now_dt, in 09:00-23:00
    # Ensure modified = created + span stays <= now_dt and inside 09:00-23:00
    created = None
    modified = None
    for _ in range(80):
        day_offset = rng.randint(0, 2)
        base_date = (now_dt - timedelta(days=day_offset)).date()
        start_hour = rng.randint(9, 21)
        m, s = pick_non_round_min_sec(rng)
        cand_created = datetime(base_date.year, base_date.month, base_date.day, start_hour, m, s)

        extra_sec = rng.choice([x for x in range(1, 59) if x % 5 != 0])
        cand_modified = cand_created + timedelta(minutes=span_minutes, seconds=extra_sec)

        # If modified passes 23:00, roll overflow into next day starting 09:05-09:49
        day_end = datetime(cand_created.year, cand_created.month, cand_created.day, 23, 0, 0)
        if cand_modified > day_end:
            overflow = cand_modified - day_end
            next_day = cand_created.date() + timedelta(days=1)
            next_start_m, next_start_s = pick_non_round_min_sec(rng)
            next_start_m = min(49, max(4, next_start_m))
            cand_modified = datetime(next_day.year, next_day.month, next_day.day, 9, next_start_m, next_start_s) + overflow
            # Ensure still within 09:00-23:00
            next_end = datetime(next_day.year, next_day.month, next_day.day, 23, 0, 0)
            if cand_modified > next_end:
                continue

        if cand_modified.minute == 0:
            cand_modified += timedelta(minutes=rng.choice([2, 3, 7]))
        if cand_modified.second == 0:
            cand_modified += timedelta(seconds=rng.choice([7, 13, 29]))

        if cand_created < cand_modified <= now_dt:
            if (now_dt - cand_created) <= timedelta(days=3):
                created = cand_created
                modified = cand_modified
                break

    if created is None or modified is None:
        # Deterministic safe fallback inside 3 days & waking hours
        ref_end = now_dt
        if ref_end.hour < 9:
            ref_end = datetime(ref_end.year, ref_end.month, ref_end.day, 22, 37, 19) - timedelta(days=1)
        elif ref_end.hour >= 23:
            ref_end = datetime(ref_end.year, ref_end.month, ref_end.day, 22, 37, 19)
        modified = ref_end - timedelta(minutes=rng.choice([11, 17, 23]), seconds=rng.choice([13, 27, 41]))
        if modified.minute == 0:
            modified -= timedelta(minutes=3)
        if modified.second == 0:
            modified -= timedelta(seconds=11)
        created = modified - timedelta(minutes=span_minutes, seconds=19)
        if created.hour < 9:
            prev_day = created.date() - timedelta(days=1)
            created = datetime(prev_day.year, prev_day.month, prev_day.day, 14, 17, 23)
            modified = created + timedelta(minutes=span_minutes, seconds=19)
            if modified > now_dt:
                modified = now_dt - timedelta(minutes=7, seconds=13)
                span_minutes = max(40, int((modified - created).total_seconds() // 60))

    effective_span = max(40, int(round((modified - created).total_seconds() / 60.0)))
    rev_interval = rng.uniform(15.0, 25.0)
    revision = max(3, int(round(effective_span / rev_interval)))

    ratio = rng.uniform(0.40, 0.70)
    total_time = int(round(effective_span * ratio))
    total_time = max(1, min(effective_span - 1, total_time))

    return {
        "created": created,
        "modified": modified,
        "span_minutes": effective_span,
        "revision": revision,
        "total_time": total_time,
    }


def _insert_rpr_font(rpr: etree._Element, tag_local: str, typeface: str) -> None:
    tag = f"{{{A_NS}}}{tag_local}"
    el = rpr.find(tag)
    if el is not None:
        el.set("typeface", typeface)
        return
    new_el = etree.Element(tag)
    new_el.set("typeface", typeface)

    # Maintain DrawingML order: latin -> ea -> cs, before sym/hlinkClick/rtl/extLst
    order_after = {
        "latin": {f"{{{A_NS}}}ea", f"{{{A_NS}}}cs"} | RPR_AFTER_FONT_TAGS,
        "ea": {f"{{{A_NS}}}cs"} | RPR_AFTER_FONT_TAGS,
        "cs": RPR_AFTER_FONT_TAGS,
    }[tag_local]

    insert_idx = len(rpr)
    for idx, child in enumerate(rpr):
        if child.tag in order_after:
            insert_idx = idx
            break
    rpr.insert(insert_idx, new_el)


def fix_fonts_in_slides(slide_trees: dict[str, etree._Element]) -> dict:
    # Pass 1: discover dominant non-YaHei CJK font and dominant Latin font per slide and deck-wide
    deck_cjk_non_yahei = Counter()
    deck_cjk_all = Counter()
    deck_latin = Counter()
    slide_cjk_non_yahei: dict[str, Counter] = {}
    slide_latin: dict[str, Counter] = {}

    for path, root in slide_trees.items():
        scjk = Counter()
        slat = Counter()
        for rpr in root.iter(f"{{{A_NS}}}rPr"):
            for slot in ("ea", "latin", "cs"):
                el = rpr.find(f"{{{A_NS}}}{slot}")
                if el is None:
                    continue
                tf = (el.get("typeface") or "").strip()
                if not tf or tf.startswith("+") or is_noto_font(tf):
                    continue
                if is_cjk_font(tf):
                    deck_cjk_all[tf] += 1
                    if not is_yahei(tf):
                        deck_cjk_non_yahei[tf] += 1
                        scjk[tf] += 1
                else:
                    deck_latin[tf] += 1
                    slat[tf] += 1
        slide_cjk_non_yahei[path] = scjk
        slide_latin[path] = slat

    default_cjk = (
        deck_cjk_non_yahei.most_common(1)[0][0]
        if deck_cjk_non_yahei
        else (deck_cjk_all.most_common(1)[0][0] if deck_cjk_all else "思源黑体")
    )
    default_latin = deck_latin.most_common(1)[0][0] if deck_latin else "Georgia"

    stats = {
        "runs_processed": 0,
        "slots_added_or_fixed": 0,
        "yahei_context_fixed": 0,
        "noto_replaced": 0,
        "default_cjk": default_cjk,
        "default_latin": default_latin,
    }

    # Pass 2: enforce 3-slot consistency on every run
    for path, root in slide_trees.items():
        ctx_cjk = (
            slide_cjk_non_yahei[path].most_common(1)[0][0]
            if slide_cjk_non_yahei[path]
            else default_cjk
        )
        ctx_latin = (
            slide_latin[path].most_common(1)[0][0]
            if slide_latin[path]
            else default_latin
        )

        for r_el in root.iter(f"{{{A_NS}}}r"):
            t_el = r_el.find(f"{{{A_NS}}}t")
            txt = (t_el.text or "") if t_el is not None else ""
            if not txt:
                continue
            stats["runs_processed"] += 1

            rpr = r_el.find(f"{{{A_NS}}}rPr")
            if rpr is None:
                rpr = etree.Element(f"{{{A_NS}}}rPr")
                r_el.insert(0, rpr)

            has_cjk = bool(CJK_CHAR_RE.search(txt))
            lat_el = rpr.find(f"{{{A_NS}}}latin")
            ea_el = rpr.find(f"{{{A_NS}}}ea")
            cs_el = rpr.find(f"{{{A_NS}}}cs")

            cur_lat = (lat_el.get("typeface") or "").strip() if lat_el is not None else ""
            cur_ea = (ea_el.get("typeface") or "").strip() if ea_el is not None else ""
            cur_cs = (cs_el.get("typeface") or "").strip() if cs_el is not None else ""

            # Replace Noto anywhere
            if is_noto_font(cur_ea):
                cur_ea = ""
                stats["noto_replaced"] += 1
            if is_noto_font(cur_lat):
                cur_lat = ""
                stats["noto_replaced"] += 1
            if is_noto_font(cur_cs):
                cur_cs = ""
                stats["noto_replaced"] += 1

            # Determine target EA font (must be CJK font, and fix YaHei if context uses another CJK font)
            target_ea = cur_ea
            if not target_ea or target_ea.startswith("+") or not is_cjk_font(target_ea):
                target_ea = ctx_cjk
            elif is_yahei(target_ea) and ctx_cjk and not is_yahei(ctx_cjk):
                target_ea = ctx_cjk
                stats["yahei_context_fixed"] += 1

            # Determine target Latin font (must NOT be CJK font)
            target_lat = cur_lat
            if not target_lat or target_lat.startswith("+") or is_cjk_font(target_lat):
                target_lat = ctx_latin

            # Determine target CS font
            target_cs = cur_cs
            if not target_cs or target_cs.startswith("+"):
                target_cs = target_ea if has_cjk else target_lat

            changed = (
                cur_lat != target_lat
                or cur_ea != target_ea
                or cur_cs != target_cs
                or lat_el is None
                or ea_el is None
                or cs_el is None
            )
            if changed:
                _insert_rpr_font(rpr, "latin", target_lat)
                _insert_rpr_font(rpr, "ea", target_ea)
                _insert_rpr_font(rpr, "cs", target_cs)
                stats["slots_added_or_fixed"] += 1

    return stats


def clean_theme_noto(theme_bytes: bytes, fallback_cjk: str, fallback_latin: str) -> tuple[bytes, int]:
    root = etree.fromstring(theme_bytes)
    replaced = 0
    for tag in ("latin", "ea", "cs", "font"):
        for el in root.iter(f"{{{A_NS}}}{tag}"):
            tf = el.get("typeface", "")
            if is_noto_font(tf):
                el.set("typeface", fallback_cjk if (tag in ("ea", "font") or is_cjk_font(tf)) else fallback_latin)
                replaced += 1
    return serialize_xml(root), replaced


def update_core_xml(
    core_bytes: bytes | None,
    title: str,
    author: str,
    created: datetime,
    modified: datetime,
    revision: int,
) -> bytes:
    if core_bytes:
        root = etree.fromstring(core_bytes)
    else:
        nsmap = {
            "cp": CP_NS,
            "dc": DC_NS,
            "dcterms": DCTERMS_NS,
            "dcmitype": "http://purl.org/dc/dcmitype/",
            "xsi": XSI_NS,
        }
        root = etree.Element(f"{{{CP_NS}}}coreProperties", nsmap=nsmap)

    def set_text(ns: str, local: str, value: str, attrs: dict | None = None) -> None:
        tag = f"{{{ns}}}{local}"
        el = root.find(tag)
        if el is None:
            el = etree.SubElement(root, tag)
        el.text = value
        if attrs:
            for k, v in attrs.items():
                el.set(k, v)

    set_text(DC_NS, "title", title)
    set_text(DC_NS, "creator", author)
    set_text(CP_NS, "lastModifiedBy", author)
    set_text(CP_NS, "revision", str(revision))
    set_text(
        DCTERMS_NS,
        "created",
        created.strftime("%Y-%m-%dT%H:%M:%SZ"),
        {f"{{{XSI_NS}}}type": "dcterms:W3CDTF"},
    )
    set_text(
        DCTERMS_NS,
        "modified",
        modified.strftime("%Y-%m-%dT%H:%M:%SZ"),
        {f"{{{XSI_NS}}}type": "dcterms:W3CDTF"},
    )

    # Clean python-pptx fingerprints or empty comments/keywords
    for ns, local in ((DC_NS, "description"), (CP_NS, "keywords"), (DC_NS, "subject")):
        el = root.find(f"{{{ns}}}{local}")
        if el is not None:
            val = (el.text or "").strip()
            low = val.lower()
            if not val or any(pat in low for pat in PLACEHOLDER_PATTERNS):
                root.remove(el)

    return serialize_xml(root)


def update_app_xml(
    app_bytes: bytes | None,
    slide_count: int,
    word_count: int,
    pres_format: str,
    total_time: int,
) -> bytes:
    if app_bytes:
        root = etree.fromstring(app_bytes)
    else:
        root = etree.Element(f"{{{EP_NS}}}Properties", nsmap={None: EP_NS})

    def set_ep(local: str, value: str) -> None:
        tag = f"{{{EP_NS}}}{local}"
        el = root.find(tag)
        if el is None:
            el = etree.SubElement(root, tag)
        el.text = value

    set_ep("TotalTime", str(total_time))
    set_ep("Words", str(word_count))
    set_ep("PresentationFormat", pres_format)
    set_ep("Slides", str(slide_count))

    return serialize_xml(root)


def parse_now(now_str: str | None) -> datetime:
    if not now_str:
        return datetime.now().replace(microsecond=0)
    for fmt in ("%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M", "%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M"):
        try:
            return datetime.strptime(now_str.strip(), fmt)
        except ValueError:
            continue
    raise ValueError(f"Invalid --now format: {now_str!r}. Use ISO format e.g. 2026-11-26T15:30")


def run_hygiene(args: argparse.Namespace) -> int:
    if not os.path.isfile(args.input):
        msg = f"Input file not found: {args.input}"
        if args.json:
            print(json.dumps({"status": "error", "error": msg}, ensure_ascii=False))
        else:
            print(f"ERROR: {msg}", file=sys.stderr)
        return 1

    try:
        now_dt = parse_now(args.now)
    except ValueError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2

    rng = random.Random(args.seed) if args.seed is not None else random.Random()

    try:
        with zipfile.ZipFile(args.input, "r") as zin:
            entries = {info.filename: zin.read(info.filename) for info in zin.infolist()}
    except zipfile.BadZipFile:
        msg = f"Not a valid .pptx zip archive: {args.input}"
        if args.json:
            print(json.dumps({"status": "error", "error": msg}, ensure_ascii=False))
        else:
            print(f"ERROR: {msg}", file=sys.stderr)
        return 1

    if "ppt/presentation.xml" not in entries:
        msg = "Invalid .pptx: missing ppt/presentation.xml"
        if args.json:
            print(json.dumps({"status": "error", "error": msg}, ensure_ascii=False))
        else:
            print(f"ERROR: {msg}", file=sys.stderr)
        return 1

    slide_paths = sorted(
        [k for k in entries if re.match(r"^ppt/slides/slide\d+\.xml$", k)],
        key=lambda p: int(re.search(r"slide(\d+)\.xml$", p).group(1)),
    )
    slide_count = len(slide_paths)
    pres_format = detect_presentation_format(entries["ppt/presentation.xml"])

    # Parse slides, count words, fix 3-slot fonts
    slide_trees = {p: etree.fromstring(entries[p]) for p in slide_paths}
    total_words = 0
    for root in slide_trees.values():
        for t_el in root.iter(f"{{{A_NS}}}t"):
            total_words += count_words(t_el.text or "")

    font_stats = fix_fonts_in_slides(slide_trees)
    for p, root in slide_trees.items():
        entries[p] = serialize_xml(root)

    # Clean Noto in theme XMLs if present
    theme_noto_replaced = 0
    for k in list(entries.keys()):
        if re.match(r"^ppt/theme/theme\d+\.xml$", k):
            entries[k], rep = clean_theme_noto(
                entries[k], font_stats["default_cjk"], font_stats["default_latin"]
            )
            theme_noto_replaced += rep
    font_stats["noto_replaced"] += theme_noto_replaced

    # Generate realistic human timestamps
    ts = generate_human_timestamps(now_dt, slide_count, rng)

    # Update core.xml & app.xml
    entries["docProps/core.xml"] = update_core_xml(
        entries.get("docProps/core.xml"),
        title=args.title,
        author=args.author,
        created=ts["created"],
        modified=ts["modified"],
        revision=ts["revision"],
    )
    entries["docProps/app.xml"] = update_app_xml(
        entries.get("docProps/app.xml"),
        slide_count=slide_count,
        word_count=total_words,
        pres_format=pres_format,
        total_time=ts["total_time"],
    )

    # Normalize XML declaration across ALL .xml and .rels entries
    xml_normalized = 0
    for k in list(entries.keys()):
        if k.endswith(".xml") or k.endswith(".rels"):
            entries[k] = normalize_xml_declaration(entries[k])
            xml_normalized += 1

    out_dir = os.path.dirname(os.path.abspath(args.out))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    with zipfile.ZipFile(args.out, "w", compression=zipfile.ZIP_DEFLATED) as zout:
        for k, data in entries.items():
            zout.writestr(k, data)

    result = {
        "status": "ok",
        "input": args.input,
        "output": args.out,
        "slides": slide_count,
        "words": total_words,
        "presentation_format": pres_format,
        "author": args.author,
        "title": args.title,
        "created": ts["created"].strftime("%Y-%m-%dT%H:%M:%SZ"),
        "modified": ts["modified"].strftime("%Y-%m-%dT%H:%M:%SZ"),
        "span_minutes": ts["span_minutes"],
        "revision": ts["revision"],
        "total_time": ts["total_time"],
        "xml_files_normalized": xml_normalized,
        "font_stats": font_stats,
    }

    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    elif args.brief:
        print(
            f"OK | slides={slide_count} | created={result['created']} | "
            f"modified={result['modified']} | rev={ts['revision']} | TotalTime={ts['total_time']}m"
        )
    else:
        print(f"Hygiene completed: {args.out}")
        print(f"  Slides: {slide_count} | Words: {total_words} | Format: {pres_format}")
        print(f"  Author: {args.author} | Title: {args.title}")
        print(
            f"  Timestamps: created={result['created']} -> modified={result['modified']} "
            f"(span={ts['span_minutes']}m, TotalTime={ts['total_time']}m, rev={ts['revision']})"
        )
        print(
            f"  Fonts: runs={font_stats['runs_processed']}, fixed={font_stats['slots_added_or_fixed']}, "
            f"yahei_ctx_fixed={font_stats['yahei_context_fixed']}, noto_replaced={font_stats['noto_replaced']}"
        )
        print(f"  XML declarations normalized: {xml_normalized}")

    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Post-processing hygiene & realistic timestamp tool for .pptx decks."
    )
    p.add_argument("input", help="Input .pptx file path")
    p.add_argument("--out", required=True, help="Output .pptx file path")
    p.add_argument("--author", required=True, help="Author / lastModifiedBy name")
    p.add_argument("--title", required=True, help="Document dc:title")
    p.add_argument("--now", default=None, help="Reference delivery time (ISO, e.g. 2026-11-26T15:30)")
    p.add_argument("--seed", type=int, default=None, help="Random seed for reproducibility")
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--brief", action="store_true", help="Output a single summary line")
    mode.add_argument("--json", action="store_true", help="Output machine-readable JSON")
    return p


if __name__ == "__main__":
    parser = build_parser()
    parsed = parser.parse_args()
    sys.exit(run_hygiene(parsed))
